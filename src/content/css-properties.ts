function normalize(value: string): string | null {
  const trimmed = value.trim();
  if (!trimmed) return null;
  return trimmed.length > 240 ? `${trimmed.slice(0, 237)}...` : trimmed;
}

export function extractCssProperties(read: StyleReader): CssProperty[] {
  const result: CssProperty[] = [];
  for (const category of CSS_CATEGORIES) {
    for (const name of PROPERTIES[category]) {
      const value = normalize(read(name));
      if (value) result.push({ name, value, category });
    }
  }
  return result;
}

export function cssDeclaration(property: CssProperty): string {
  return `${property.name}: ${property.value};`;
}
